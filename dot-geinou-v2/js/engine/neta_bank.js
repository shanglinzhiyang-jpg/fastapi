// Candidate parts for the editor's 「部品から足す」: [{ id, label, items: [{ text, role, beat, type, pair? }] }]
// opts: { themeId, era, year, dialect, names, roles: { boke, tsukkomi } , seed }
export function partsFor(kind, opts = {}) {
  const era = opts.era || 'reiwa';
  const year = opts.year || ERA_YEAR[era];
  const dia = (s) => fillDialect(fillNames(fillEra(s, era), opts.names), opts.dialect);
  const r = rngFor(opts.seed || 1);
  const tabs = [];
  const th = theme(opts.themeId) || themesFor(kind, era)[0];
  const others = shuffled(themesFor(kind, era).filter((t) => t !== th), r).slice(0, 4);
  const pair = (e, beat = 'boke') => ({ text: dia(e.boke), role: 'boke', beat, type: e.type, pair: e.tsukkomi ? { text: dia(e.tsukkomi), role: 'tsukkomi', beat: 'tsukkomi', type: e.type } : null });
  const bokeOf = (t) => t.boke.map(parseEntry).filter((e) => yearOk(e, year));
  if (kind === 'manzai' || kind === 'any') {
    tabs.push({ id: 'tsukami', label: 'ツカミ', items: [...TSUKAMI.map((s) => ({ text: dia(s), role: 'boke', beat: 'tsukami', type: '' })), ...TSUKAMI_BOKE.map((s) => pair(parseEntry(s), 'tsukami'))] });
    tabs.push({ id: 'furi', label: 'フリ・設定', items: [...th.furi.map((s) => ({ text: dia(s), role: 'boke', beat: 'setup', type: '' })), ...others.flatMap((t) => t.furi.slice(0, 1).map((s) => ({ text: dia(s), role: 'boke', beat: 'setup', type: '', theme: t.name })))] });
    tabs.push({ id: 'boke', label: 'ボケ', items: [...bokeOf(th).map((e) => pair(e)), ...others.flatMap((t) => bokeOf(t).slice(0, 3).map((e) => ({ ...pair(e), theme: t.name })))] });
    tabs.push({ id: 'tsukkomi', label: 'ツッコミ', items: [...bokeOf(th).map((e) => ({ text: dia(e.tsukkomi), role: 'tsukkomi', beat: 'tsukkomi', type: e.type })), ...TATOE.map((s) => ({ text: dia(s), role: 'tsukkomi', beat: 'tsukkomi', type: 'ta' })), ...NORI.map((s) => ({ text: dia(s), role: 'tsukkomi', beat: 'tsukkomi', type: 'no' })), ...TSUKKOMI_STOCK.map((s) => ({ text: dia(s), role: 'tsukkomi', beat: 'tsukkomi', type: 'stock' }))] });
    tabs.push({ id: 'tenkai', label: '展開', items: TENKAI.map((s) => ({ text: dia(s), role: 'tsukkomi', beat: 'tenkai', type: '' })) });
    const tp = th.tendon;
    tabs.push({ id: 'tendon', label: '天丼', items: [
      ...(tp ? [{ text: dia(tendonLine(tp, 0)), role: 'boke', beat: 'tendon', type: 'te', pair: { text: dia(TENDON_TSUKKOMI[0]), role: 'tsukkomi', beat: 'tsukkomi', type: 'te' } }, { text: dia(tendonLine(tp, 1)), role: 'boke', beat: 'tendon', type: 'te', pair: { text: dia(TENDON_TSUKKOMI[2]), role: 'tsukkomi', beat: 'tsukkomi', type: 'te' } }] : []),
      ...TENDON_TSUKKOMI.map((s) => ({ text: dia(s), role: 'tsukkomi', beat: 'tsukkomi', type: 'te' })),
    ] });
    if (th.fukusen) {
      const k = parseEntry(th.fukusen[1]);
      tabs.push({ id: 'fukusen', label: '伏線・回収', items: [{ text: dia(th.fukusen[0]), role: 'boke', beat: 'fukusen', type: '' }, { ...pair(k, 'kaishu') }] });
    }
    tabs.push({ id: 'ochi', label: 'オチ', items: [...th.ochi.map((s) => pair(parseEntry(s), 'ochi')), ...others.flatMap((t) => t.ochi.map((s) => ({ ...pair(parseEntry(s), 'ochi'), theme: t.name }))), ...CLOSER.map((s) => ({ text: dia(s), role: 'tsukkomi', beat: 'ochi', type: '' }))] });
    return tabs;
  }
  const kindParts = KIND_PARTS[kind];
  return kindParts ? kindParts(opts, { era, year, dia, r, th, others, bokeOf }) : [];
}

