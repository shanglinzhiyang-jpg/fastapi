export function fillEra(text, era = 'reiwa') {
  return String(text || '').replace(/\{(\w+)\}/g, (m, k) => (ERA_WORDS[k] ? ERA_WORDS[k][era] || ERA_WORDS[k].reiwa : m));
}
// {unit} {boke} {tsukkomi} {name}: the act's names at insertion time.
export function fillNames(text, names = {}) {
  let s = String(text || '');
  if (!names.unit) s = s.replace(/\{unit\}です！/g, '').replace(/、\{unit\}です。/g, '。');
  return s
    .replaceAll('{unit}', names.unit || 'ぼくたち')
    .replaceAll('{boke}', names.boke || 'ボケ担当')
    .replaceAll('{tsukkomi}', names.tsukkomi || 'ツッコミ担当')
    .replaceAll('{name}', names.name || 'ぼく');
}

// Standard Japanese → Kansai-ben (a handful of reliable endings; good enough for the generated candidates).
const KANSAI_RULES = [
  [/いいかげんにしろ|いい加減にしろ/g, 'ええかげんにせえ'], [/もういいよ/g, 'もうええわ'], [/なんでだよ/g, 'なんでやねん'],
  [/どういうことだよ/g, 'どういうことやねん'], [/そんなわけないだろ/g, 'そんなわけあるかい'], [/ありえないだろ/g, 'ありえへんやろ'],
  [/聞いたことないよ/g, '聞いたことないわ'], [/てんじゃねえか/g, 'てるやないか'], [/じゃねえか/g, 'やないか'], [/じゃないか/g, 'やないか'], [/じゃないんだから/g, 'やないんやから'],
  [/じゃないよ/g, 'ちゃうわ'], [/じゃない！/g, 'ちゃうわ！'], [/じゃん/g, 'やん'], [/だろ([！!？?]|$)/g, 'やろ$1'], [/でしょ/g, 'やろ'],
  [/([ぁ-んァ-ヶー一-龯])だよ！/g, '$1やねん！'], [/([ぁ-んァ-ヶー一-龯])だよ。/g, '$1やで。'], [/なんだよ/g, 'やねん'],
  [/([らりるれろかきくけこさしすせそたちつてとなにぬねのまみむめもがぎぐげごばびぶべぼ])ないよ！/g, '$1へんわ！'],
  [/できないよ/g, 'できへんわ'], [/しないよ/g, 'せえへんわ'], [/来ないよ/g, '来えへんわ'], [/いないよ/g, 'おらんわ'],
  [/んですよ。/g, 'んですわ。'], [/んですよ！/g, 'んですわ！'], [/てるんだ。/g, 'てんねん。'], [/なんだ。/g, 'やねん。'],
  [/すんな！/g, 'すな！'], [/するな！/g, 'すな！'], [/しろよ！/g, 'せえや！'], [/しろ！/g, 'せえ！'], [/かよ！/g, 'かい！'],
  [/んだよ！/g, 'ねん！'], [/だから/g, 'やから'], [/本当に/g, 'ほんまに'], [/すごく/g, 'めっちゃ'], [/ちがう/g, 'ちゃう'], [/違う/g, 'ちゃう'],
  [/ばかだねえ/g, 'あほやなあ'], [/ばか/g, 'あほ'], [/いいね/g, 'ええな'], [/いいよ/g, 'ええよ'],
];
export function toKansai(s) {
  let t = String(s || '');
  for (const [re, to] of KANSAI_RULES) t = t.replace(re, to);
  return t;
}
export const fillDialect = (s, dialect) => (dialect === 'kansai' ? toKansai(s) : String(s || ''));

