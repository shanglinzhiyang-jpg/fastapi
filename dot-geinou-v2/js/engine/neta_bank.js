export function hashStr(s) { let h = 2166136261; for (const ch of String(s)) { h ^= ch.codePointAt(0); h = Math.imul(h, 16777619); } return h >>> 0; }
export function rngFor(seed) { return mulberry32(typeof seed === 'number' ? seed : hashStr(seed)); }
const pickR = (arr, r) => arr[Math.floor(r() * arr.length)];
function shuffled(arr, r) { const a = arr.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; }
const yearOk = (e, year) => !e.from || !year || year >= e.from;
// The 天丼 line: the boke says the phrase again (n = 0: the second time, 1: the third).
export const tendonLine = (tp, n = 0) => { const e = /[。！？」]$/.test(tp) ? '' : '。'; return n ? `最後にもう一回…${tp}${e}` : `…${tp}${e}`; };

