// buildAuto(kind, { quality 0..100, era, year, dialect, names, seed, themeId, length (sec) }) → { title, theme, setting, chars, lines }
export function buildAuto(kind, opts = {}) {
  const q = Math.max(0, Math.min(100, Number(opts.quality ?? 50)));
  const era = opts.era || 'reiwa';
  const year = opts.year || ERA_YEAR[era];
  const r = rngFor(opts.seed ?? `${kind}:${q}:${era}`);
  const dia = (s) => fillDialect(fillNames(fillEra(s, era), opts.names), opts.dialect);
  const len = Number(opts.length) || DEFAULT_LEN[kind] || 240;
  if (kind === 'manzai' || kind === 'any' || !KIND_AUTO[kind]) {
    const pool = themesFor('manzai', era);
    const th = theme(opts.themeId) || pickR(pool, r);
    const lines = [];
    lines.push(L('boke', dia(pickR(TSUKAMI, r)), 'tsukami'));
    if (q >= 45) { const e = parseEntry(pickR(TSUKAMI_BOKE, r)); lines.push(L('boke', dia(e.boke), 'tsukami', { type: e.type })); lines.push(L('tsukkomi', dia(e.tsukkomi), 'tsukkomi')); }
    lines.push(L('boke', dia(th.furi[0]), 'setup'));
    // about one ボケ + ツッコミ per 9–10 seconds of a 4-minute 漫才, fewer for a weak act
    const want = Math.max(3, Math.round((len / 60) * (q >= 70 ? 5 : q >= 45 ? 4 : 3)));
    const own = th.boke.map(parseEntry).filter((e) => yearOk(e, year));
    const extra = shuffled(pool.filter((t) => t !== th), r).flatMap((t) => t.boke.map(parseEntry).filter((e) => yearOk(e, year)));
    let bokes = [...shuffled(own, r), ...(q < 40 ? extra : [])].slice(0, want);
    // the boke that has the 天丼 phrase comes first, so the repeats call back to it
    const tIdx = th.tendon ? own.findIndex((e) => e.boke.includes(th.tendon)) : -1;
    if (q >= 60 && tIdx >= 0) bokes = [own[tIdx], ...bokes.filter((e) => e !== own[tIdx])].slice(0, want);
    const tendonAt = q >= 60 && th.tendon ? [Math.floor(bokes.length * 0.45), Math.floor(bokes.length * 0.8)] : [];
    const fuku = q >= 70 && th.fukusen;
    bokes.forEach((e, i) => {
      if (fuku && i === 1) lines.push(L('boke', dia(th.fukusen[0]), 'fukusen'));
      if (q >= 55 && i === Math.floor(bokes.length / 2)) lines.push(L('tsukkomi', dia(pickR(TENKAI, r)), 'tenkai'));
      lines.push(L('boke', dia(e.boke), 'boke', { type: e.type }));
      // a weak act leans on the stock ツッコミ
      lines.push(L('tsukkomi', dia(q < 35 && r() < 0.6 ? pickR(TSUKKOMI_STOCK, r) : e.tsukkomi), 'tsukkomi'));
      const ti = tendonAt.indexOf(i);
      if (ti >= 0) { lines.push(L('boke', dia(tendonLine(th.tendon, ti)), 'tendon', { type: 'te' })); lines.push(L('tsukkomi', dia(TENDON_TSUKKOMI[ti ? 2 : 0]), 'tsukkomi')); }
    });
    if (fuku) { const k = parseEntry(th.fukusen[1]); lines.push(L('boke', dia(k.boke), 'kaishu', { type: 'fk' })); lines.push(L('tsukkomi', dia(k.tsukkomi), 'tsukkomi')); }
    const o = parseEntry(th.ochi[0]);
    lines.push(L('boke', dia(o.boke), 'ochi', { type: o.type }));
    lines.push(L('tsukkomi', dia(`${o.tsukkomi.replace(/！$/, '')}！${CLOSER[Math.floor(r() * CLOSER.length)].replace(/^[^！]*！/, '')}`), 'ochi'));
    return { title: th.name, theme: th.name, themeId: th.id, setting: '', lines };
  }
  return KIND_AUTO[kind]({ q, era, year, r, dia, len, opts });
}
export const DEFAULT_LEN = { manzai: 240, conte: 300, pin: 240, rakugo: 900, ogiri: 120, utaneta: 180, monomane: 180, talk: 120, any: 240 };

const KIND_AUTO = {
  conte({ q, era, r, dia, opts }) {
    const pool = CONTE.filter((c) => !c.eras || c.eras.includes(era));
    const c = pool.find((x) => x.id === opts.themeId) || pickR(pool, r);
    let lines = c.lines.map(([role, text, beat, tw]) => L(role, dia(text), beat === 'uragiri' ? 'tenkai' : beat, beat === 'uragiri' || tw ? { twist: true } : {}));
    if (q < 45) lines = lines.filter((x, i) => !x.twist && (i % 4 !== 3 || x.beat === 'ochi'));
    return { title: c.title, theme: c.title, themeId: c.id, setting: c.setting, chars: { ...c.chars }, lines };
  },
  pin({ q, r, dia, opts }) {
    const p = PIN.find((x) => x.id === opts.themeId) || pickR(PIN, r);
    let lines = p.lines.map(([role, text, beat]) => L(role, dia(text), beat));
    if (q < 45) lines = lines.filter((x) => x.beat !== 'tendon');
    return { title: p.title, theme: p.title, themeId: p.id, setting: p.setting || '', lines };
  },
  rakugo({ q, r, dia, opts }) {
    const h = RAKUGO.hondai.find((x) => x.id === opts.themeId) || pickR(RAKUGO.hondai, r);
    const mk = shuffled(RAKUGO.makura, r).slice(0, q >= 60 ? 3 : 2).map((s) => L('narr', dia(s), 'makura'));
    const lines = [...mk, ...h.lines.map(([role, text, beat]) => L(role, dia(text), beat || 'hondai'))];
    return { title: h.title, theme: h.title, themeId: h.id, setting: '', chars: { ...h.chars }, lines };
  },
  ogiri({ q, era, year, r, dia, opts }) {
    const pool = OGIRI.filter((o) => !o.from || year >= o.from);
    const o = pool.find((x) => x.id === opts.themeId) || pickR(pool, r);
    const own = shuffled(o.answers, r);
    const n = q >= 70 ? 5 : q >= 45 ? 4 : 3;
    return { title: dia(o.odai), theme: dia(o.odai), themeId: o.id, setting: '', lines: own.slice(0, n).map((s) => L('pin', dia(s), 'answer')) };
  },
  utaneta({ year, r, dia, opts }) {
    const pool = UTA.filter((u) => !u.from || year >= u.from);
    const u = pool.find((x) => x.id === opts.themeId) || pickR(pool, r);
    return { title: u.title, theme: u.title, themeId: u.id, setting: '', lines: u.lines.map(([role, text, beat]) => L(role, dia(text), beat)) };
  },
  monomane({ year, r, dia, opts }) {
    const pool = MONOMANE.filter((m) => !m.from || year >= m.from);
    const m = pool.find((x) => x.id === opts.themeId) || pickR(pool, r);
    return { title: `${m.target}のものまね`, theme: m.target, themeId: m.id, setting: '', lines: m.lines.map(([role, text, beat]) => L(role, dia(text), beat)) };
  },
  talk({ r, dia, opts }) {
    const t = TALK.find((x) => x.id === opts.themeId) || pickR(TALK, r);
    return { title: dia(t.title), theme: dia(t.title), themeId: t.id, setting: '', lines: t.lines.map(([role, text, beat]) => L(role, dia(text), beat)) };
  },
};

// Every line of the bank in every era and both dialects (the AI's 「部品の丸写し」 check and its kana model).
let CORPUS = null;
export function bankCorpus() {
  if (CORPUS) return CORPUS;
  const raw = [];
  const add = (s) => { if (s) raw.push(String(s)); };
  for (const t of THEMES) {
    t.furi.forEach(add);
    for (const s of [...t.boke, ...t.ochi, t.fukusen ? t.fukusen[1] : '']) { const e = parseEntry(s); add(e.boke); add(e.tsukkomi); }
    if (t.fukusen) add(t.fukusen[0]);
  }
  for (const s of [...TSUKAMI_BOKE]) { const e = parseEntry(s); add(e.boke); add(e.tsukkomi); }
  [...TENKAI, ...TENDON_TSUKKOMI, ...TATOE, ...NORI].forEach(add);
  for (const c of CONTE) { add(c.setting); c.lines.forEach((l) => add(l[1])); }
  for (const p of PIN) p.lines.forEach((l) => add(l[1]));
  RAKUGO.makura.forEach(add); RAKUGO.close.forEach(add);
  for (const h of RAKUGO.hondai) h.lines.forEach((l) => add(l[1]));
  for (const o of OGIRI) { add(o.odai); o.answers.forEach(add); }
  for (const u of UTA) u.lines.forEach((l) => add(l[1]));
  for (const m of MONOMANE) m.lines.forEach((l) => add(l[1]));
  for (const t of TALK) t.lines.forEach((l) => add(l[1]));
  const out = new Set();
  for (const s of raw) {
    const eras = s.includes('{') ? ERA_IDS : ['reiwa'];
    for (const e of eras) { const f = fillNames(fillEra(s, e)); out.add(f); const k = toKansai(f); if (k !== f) out.add(k); }
  }
  CORPUS = [...out];
  return CORPUS;
}
