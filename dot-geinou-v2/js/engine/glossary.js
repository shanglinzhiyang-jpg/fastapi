// ---------------------------------------------------------------- helpers
export function termStatus(entry, year, ctx = null) {
  if (!entry) return 'now';
  if (typeof entry.status === 'function') {
    try { const s0 = entry.status(year, ctx); if (s0 === 'now' || s0 === 'future' || s0 === 'past') return s0; } catch (e) { /* fall back */ }
  }
  if (entry.since && year < entry.since) return 'future';
  if (entry.until && year >= entry.until) return 'past';
  return 'now';
}
export function termText(entry, year = 2026, ctx = null) {
  if (!entry) return '';
  try { return typeof entry.long === 'function' ? entry.long(year, ctx) : String(entry.long || ''); } catch (e) { return String(entry.short || ''); }
}
const labelOf = (v, year, ctx, d) => { try { return typeof v === 'function' ? v(year, ctx) : v || d; } catch (e) { return d; } };
// The 「…から」 / 「…まで」 texts of an entry for that year (and game).
export function termSince(entry, year, ctx = null) { return entry ? labelOf(entry.sinceText, year, ctx, entry.since ? `${entry.since}年` : '') : ''; }
export function termUntil(entry, year, ctx = null) { return entry ? labelOf(entry.untilText, year, ctx, entry.until ? `${entry.until}年まで` : '') : ''; }
// The term for that era: an entry that does not exist yet gives way to its earlier name (prev), one that
// is history gives way to its later name only when asked (opts.later). 財務省原案 in 1990 → 大蔵原案.
export function eraTerm(term, year, ctx = null, opts = {}) {
  const e = glossaryLookup(term);
  if (!e) return term;
  const st = termStatus(GLOSSARY[e.term], year, ctx);
  if (st === 'future' && e.prev && GLOSSARY[e.prev]) return e.prev;
  if (st === 'past' && opts.later && e.next && GLOSSARY[e.next]) return e.next;
  return e.term;
}
export function glossaryLookup(term) {
  if (term == null) return null;
  const t = String(term).trim();
  if (!t) return null;
  if (GLOSSARY[t]) return { term: t, ...GLOSSARY[t] };
  const a = GLOSSARY_ALIAS[t];
  if (a && GLOSSARY[a]) return { term: a, ...GLOSSARY[a] };
  // loose: a term inside the text, or the text inside a term (the longest wins)
  let best = null;
  for (const k of Object.keys(GLOSSARY)) {
    if (k.includes(t) || t.includes(k)) { if (!best || Math.abs(k.length - t.length) < Math.abs(best.length - t.length)) best = k; }
  }
  return best ? { term: best, ...GLOSSARY[best] } : null;
}
// Terms (keys and aliases → their term) that appear in a text, longest first, without overlaps.
let FIND_KEYS = null;
export function glossaryFind(text, year = null, ctx = null) {
  const s = String(text || '');
  if (!FIND_KEYS) {
    FIND_KEYS = [...Object.keys(GLOSSARY).map((k) => [k, k]), ...Object.entries(GLOSSARY_ALIAS).filter(([, v]) => GLOSSARY[v]).map(([k, v]) => [k, v])]
      .filter(([k]) => k.length >= 2).sort((a, b) => b[0].length - a[0].length);
  }
  const used = new Array(s.length).fill(false);
  const out = [];
  for (const [k, term] of FIND_KEYS) {
    let i = s.indexOf(k);
    while (i >= 0) {
      let free = true;
      for (let j = i; j < i + k.length; j++) if (used[j]) { free = false; break; }
      if (free) {
        for (let j = i; j < i + k.length; j++) used[j] = true;
        if (!out.some((o) => o.term === term) && (year == null || termStatus(GLOSSARY[term], year, ctx) !== 'future')) out.push({ term, at: i, word: k });
      }
      i = s.indexOf(k, i + k.length);
    }
  }
  return out.sort((a, b) => a.at - b.at);
}
export function glossaryTermsByCat(cat) { return Object.keys(GLOSSARY).filter((k) => GLOSSARY[k].cat === cat); }
// 50音順 (by kana)
export function glossaryKanaOrder() { return Object.keys(GLOSSARY).sort((a, b) => GLOSSARY[a].kana.localeCompare(GLOSSARY[b].kana, 'ja')); }
