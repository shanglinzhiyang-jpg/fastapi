// 衆議院・参議院の定数（全体）by year (real figures; the politics core uses the same steps)
function shugiTotal(y) { return y < 1993 ? 512 : y < 1996 ? 511 : y < 2000 ? 500 : y < 2014 ? 480 : y < 2017 ? 475 : 465; }
function sangiTotal(y) { return y < 2001 ? 252 : y < 2004 ? 247 : y < 2019 ? 242 : y < 2022 ? 245 : 248; }
const vAge = (y) => (y >= 2016 ? 18 : 20);
// Has the date (Y, M) come in the game year y (month from ctx when known; a whole year otherwise)?
const done = (y, c, Y, M = 1) => y > Y || (y === Y && (c && c.month ? c.month >= M : true));
// The real 消費税 steps (1989-04 3%, 1997-04 5%, 2014-04 8%, 2019-10 10%).
const TAX_STEPS = [[1989, 4, 3, '1989年4月に3%'], [1997, 4, 5, '1997年4月に5%'], [2014, 4, 8, '2014年4月に8%'], [2019, 10, 10, '2019年10月に10%']];
const realTax = (y, c) => { let r0 = 0; for (const [Y, M, v] of TAX_STEPS) if (done(y, c, Y, M)) r0 = v; return r0; };
const taxRate = (y, c) => (c && Number.isFinite(Number(c.taxRate)) ? Number(c.taxRate) : realTax(y, c));
// A fact after the era's first year may not have happened in this game: say 「実際の日本では」.
const realSays = (c, Y) => (c && c.startYear != null && Y > c.startYear ? '実際の日本では、' : '');
// The 衆議院 system: the sitting House (now) and the next election (next), from ctx or the real dates.
const shugiNow = (y, c) => (c && c.shugi && c.shugi.now ? c.shugi.now : y >= 1996 ? 'heiritsu' : 'chusenkyoku');
const shugiNext = (y, c) => (c && c.shugi && c.shugi.next ? c.shugi.next : y >= 1995 ? 'heiritsu' : 'chusenkyoku');
const heiritsuSince = (y) => (y < 1996 ? '並立制の導入' : '1996年');
const heiritsuStatus = (y, c) => (c && c.shugi ? (shugiNow(y, c) === 'heiritsu' || shugiNext(y, c) === 'heiritsu' ? 'now' : 'future') : null);
const postalOf = (c) => (c && c.postal && c.postal.stage ? c.postal : null);
const ymText = (o) => `${o.year}年${o.month ? `${o.month}月` : ''}`;

