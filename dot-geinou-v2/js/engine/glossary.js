//
//   GLOSSARY[term] = { kana, cat, short, long, since?, sinceText?, until?, untilText?, related[], alias? }
//     kana       よみがな
//     cat        category id (GLOSSARY_CATS)
//     short      one line (≈30字)
//     long       a plain explanation (やさしい日本語, readings for hard words). A string, or
//                (year, ctx) => string when the facts depend on the game year or on the game itself.
//                A fact later than the game year is never stated as history (it is left out, or
//                said as a plan already set by law); 「いま」 values come from ctx (the game state).
//     since      the year the thing began (law in force, office set up …); before it the term is
//                「この時代にはまだない」 (the app hides it unless the player asks to see such terms)
//     until      the year it ended (shown as history: 「〜YYYY年」)
//     status     optional (year, ctx) => 'now' | 'future' | 'past' | null: the game state overrides
//                since/until (e.g. the player enacted 18歳選挙権 before 2016)
//     sinceText / untilText: a string or (year, ctx) => string
//     prev / next: the term with the same role in an earlier / later era (大蔵原案 → 財務省原案)
//     related    other GLOSSARY terms
//   ctx (all fields optional; built by assist.js from g.pol() / g.govt() / g.postal() / g.regime(),
//   feature-detected; without it the real timeline is used):
//     { year, month, startYear (the era's first year), taxRate (消費税 %), taxPlan { rate, year, month },
//       reducedRate, votingAge, age18, heiritsuLaw, shugi { now, next, total, smd, pr }, referendumLaw,
//       amendments: [names], emergencyClause: name | null, postal { stage, law, privatized } }
//   GLOSSARY_CATS: [{ id, name, color }] in display order.
//   glossaryLookup(term) → { term, ...entry } | null (exact, alias, then a loose match)
//   glossaryFind(text, year?, ctx?) → terms that appear in text (longest first, no overlaps)
//   termStatus(entry, year, ctx?) → 'now' | 'future' | 'past'
//   termText(entry, year, ctx?) → the long text for that year (and game)
//   termSince(entry, year, ctx?) / termUntil(entry, year, ctx?) → the label texts
//   eraTerm(term, year, ctx?) → the term for that era (大蔵原案 before 2001 for 財務省原案 …)
