export function fiveWrong(ch, rng = Math.random) {
  const out = [];
  const add = (c) => { if (c && c !== ch && !out.includes(c) && out.length < 3) out.push(c); };
  const groups = KANA_GROUPS.filter((g) => g.includes(ch));
  const near = [];
  for (const gr of groups) for (const c of gr) if (c !== ch) near.push(c);
  for (let i = near.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [near[i], near[j]] = [near[j], near[i]]; }
  near.forEach(add);
  let guard = 0;
  while (out.length < 3 && guard++ < 200) add(KANA_POOL[Math.floor(rng() * KANA_POOL.length)]);
  return out;
}

