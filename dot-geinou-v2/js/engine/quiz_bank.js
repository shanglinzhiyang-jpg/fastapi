// ======================================================================== generated 計算 (always correct)
export function genKeisan(rng = Math.random, lv = 2) {
  const R = (a, b) => a + Math.floor(rng() * (b - a + 1));
  let q, a;
  const kind = R(0, lv >= 3 ? 4 : lv >= 2 ? 3 : 1);
  if (kind === 0) { const x = R(12, 89), y = R(12, 89); q = `${x}＋${y} は？`; a = x + y; }
  else if (kind === 1) { const x = R(31, 99), y = R(12, x - 5); q = `${x}−${y} は？`; a = x - y; }
  else if (kind === 2) { const x = R(12, 29), y = R(3, 9); q = `${x}×${y} は？`; a = x * y; }
  else if (kind === 3) { const y = R(3, 9), a0 = R(6, 19); q = `${a0 * y}÷${y} は？`; a = a0; }
  else { const x = R(2, 9) * 100, p = R(1, 4) * 10; q = `${x}円の${p}%は何円？`; a = (x * p) / 100; }
  const near = new Set();
  for (const d of [1, -1, 2, 10, -10, -2, 3, 5]) { const v = a + d; if (v > 0 && v !== a) near.add(v); if (near.size >= 3) break; }
  const unit = /円/.test(q) ? '円' : '';
  const w = [...near].slice(0, 3).map((v) => `${v}${unit}`);
  return { id: `keisan:gen`, cat: 'keisan', q, a: `${a}${unit}`, w, lv, from: 0, to: 9999, gen: true };
}

// ======================================================================== picking
// pick({ cats, n, year, lv (target 1..3), rng, avoid: Set<id>, prefer: [ids] (asked first, e.g. a review) })
export function pick(o = {}) {
  const rng = o.rng || Math.random;
  const cats = (o.cats && o.cats.length ? o.cats : CAT_IDS).filter((c) => CATS[c]);
  const n = Math.max(1, o.n | 0 || 5);
  const target = o.lv || 2;
  const avoid = o.avoid || new Set();
  const out = [];
  const used = new Set();
  for (const id of o.prefer || []) {
    const x = BY_ID.get(id);
    if (x && qOk(x, o.year) && cats.includes(x.cat) && !used.has(id)) { out.push(x); used.add(id); }
    if (out.length >= n) return out;
  }
  const pool = QUESTIONS.filter((x) => cats.includes(x.cat) && qOk(x, o.year) && !used.has(x.id))
    .map((x) => ({ x, k: Math.abs(x.lv - target) * 0.9 + (avoid.has(x.id) ? 3 : 0) + rng() * 1.8 }));
  const perCat = {};
  while (out.length < n && (pool.length || cats.includes('keisan'))) {
    // spread over the categories; 計算 also comes from the generator
    const genTurn = cats.includes('keisan') && (perCat.keisan || 0) < Math.ceil(n / cats.length) && rng() < 0.5 / cats.length * 2;
    if (genTurn || !pool.length) { out.push(genKeisan(rng, target)); perCat.keisan = (perCat.keisan || 0) + 1; continue; }
    let best = 0, bk = Infinity;
    pool.forEach((it, i) => { const k = it.k + (perCat[it.x.cat] || 0) * 1.2; if (k < bk) { bk = k; best = i; } });
    const [it] = pool.splice(best, 1);
    perCat[it.x.cat] = (perCat[it.x.cat] || 0) + 1;
    out.push(it.x);
  }
  return out;
}
// A question as shuffled choices: { q, choices: [4], answer, src }
export function asChoices(x, rng = Math.random, n = 4) {
  const opts = [x.a, ...x.w.slice(0, n - 1)];
  const idx = opts.map((_, i) => i);
  for (let i = idx.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [idx[i], idx[j]] = [idx[j], idx[i]]; }
  return { q: x.q, choices: idx.map((i) => opts[i]), answer: idx.indexOf(0), src: x };
}

