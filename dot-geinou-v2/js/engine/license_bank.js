export const BANK = RAW.map((r, i) => ({
  id: 'lq' + String(i + 1).padStart(3, '0'), q: r[0], a: !!r[1], why: r[2], cat: r[3], from: r[4] || 0, to: r[5] || 999912, pts: r[6] || 1,
}));
export const qOk = (q, ym) => ym >= q.from && ym <= q.to;

const POOL_CATS = {
  kari: ['shingo', 'tsuko', 'tomaru', 'koten', 'kokoro', 'kozo', 'koso', 'yoru'],
  hon: ['shingo', 'tsuko', 'tomaru', 'koten', 'kokoro', 'kozo', 'koso', 'yoru'],
  gentsuki: ['shingo', 'tsuko', 'tomaru', 'koten', 'kokoro', 'kozo', 'yoru', 'gen'],
  nirin: ['shingo', 'tsuko', 'tomaru', 'koten', 'kokoro', 'kozo', 'koso', 'yoru', 'nirin'],
  second: ['shingo', 'tsuko', 'tomaru', 'koten', 'kokoro', 'kozo', 'koso', 'yoru', 'second'],
};
export function poolFor(kind, ym) {
  const cats = POOL_CATS[kind] || POOL_CATS.kari;
  return BANK.filter((q) => cats.includes(q.cat) && qOk(q, ym));
}
function shuffle(a, rng) {
  const r = rng || Math.random;
  const out = a.slice();
  for (let i = out.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [out[i], out[j]] = [out[j], out[i]]; }
  return out;
}
// n questions: 本免 / 第二種 take 5 危険予測 (2点) and the rest ordinary; 仮免 / 原付 / 二輪 only ordinary ones.
// A 第二種 exam also takes at least 8 旅客 questions when the date has enough of them.
export function draw(kind, ym, n = 50, rng = Math.random) {
  const pool = poolFor(kind, ym);
  const kiken = BANK.filter((q) => q.cat === 'kiken' && qOk(q, ym));
  const plain = pool.filter((q) => q.cat !== 'kiken');
  const wantK = kind === 'hon' || kind === 'second' ? Math.min(5, kiken.length) : 0;
  const picked = [];
  if (kind === 'second') picked.push(...shuffle(plain.filter((q) => q.cat === 'second'), rng).slice(0, 8));
  const rest = shuffle(plain.filter((q) => !picked.includes(q)), rng);
  picked.push(...rest.slice(0, Math.max(0, n - wantK - picked.length)));
  const list = shuffle([...picked, ...shuffle(kiken, rng).slice(0, wantK)], rng).slice(0, n);
  return list;
}
export const examMax = (list) => list.reduce((a, q) => a + (q.pts || 1), 0);
export const passPts = (list) => Math.ceil(examMax(list) * 0.9 - 1e-9);
// 学科教習 (a lesson): n questions of the given categories
export function lessonSet(cats, ym, n = 5, rng = Math.random) {
  const pool = BANK.filter((q) => cats.includes(q.cat) && qOk(q, ym));
  return shuffle(pool, rng).slice(0, n);
}
// A question as the 'quiz' minigame's custom question (2 choices, ○ first / × second; shuffle off)
export function asQuizQuestion(q) {
  return { q: q.q, choices: ['○　正しい', '×　誤り'], answer: q.a ? 0 : 1 };
}
