// the stammer shown when a line is 噛まれる: 'ありがとうございます' → 'ありがとうごじゃ…ございます'
export function kamiText(text, rng = Math.random) {
  const chars = Array.from(String(text));
  if (chars.length < 6) return text;
  const at = Math.max(2, Math.min(chars.length - 3, Math.floor(chars.length * (0.3 + rng() * 0.4))));
  const head = chars.slice(0, at).join('');
  const w = chars.slice(at, at + 2).join('');
  const SWAP = { さ: 'しゃ', す: 'しゅ', そ: 'しょ', ざ: 'じゃ', ず: 'じゅ', ぞ: 'じょ', ら: 'りゃ', る: 'りゅ', ろ: 'りょ', た: 'ちゃ', つ: 'ちゅ', と: 'ちょ' };
  const first = Array.from(w)[0];
  const bad = (SWAP[first] || first + 'っ') + '…';
  return head + bad + chars.slice(at).join('');
}

// ------------------------------------------------------------------ building a neta from the bank
const ROLE = { B: 'boke', T: 'tsukkomi', P: 'pin', N: 'narr' };
function rows(def, dialect, extra = {}) {
  return def.lines.map(([r, t, beat, x]) => ({ role: ROLE[r] || r, text: sel(t, dialect), beat, ...(x || {}), ...extra }));
}
const est = (lines) => Math.round(lines.reduce((s, l) => s + Math.max(1.4, Array.from(l.text || '').length / 6.5), 0));
const pickOf = (arr, rng, title) => (title && arr.find((x) => x.title === title)) || arr[Math.floor(rng() * arr.length)];

// A complete neta from the bank. kind: manzai | conte | rakugo | pin (style) | utaneta | monomane | talk | ogiri
export function bankNeta(kind, o = {}) {
  const rng = o.rng || Math.random;
  const dialect = o.dialect === 'std' ? 'std' : 'kansai';
  let def, lines;
  if (kind === 'conte') {
    def = pickOf(CONTE, rng, o.title);
    lines = def.lines.map(([r, t, beat, x]) => ({ role: r === 'N' ? 'narr' : r, text: t, beat, char: def.roles[r] || null, ...(x || {}) }));
  } else if (kind === 'rakugo') {
    def = pickOf(RAKUGO, rng, o.title);
    lines = def.lines.map(([r, t, beat, x]) => ({ role: r === 'N' ? 'narr' : r === 'c' ? 'c' : r, text: t, beat, char: def.chars[r] || null, ...(x || {}) }));
  } else if (kind === 'ogiri') {
    const od = pickOf(ODAI, rng, o.title);
    return { id: 'house', kind, title: od.q, theme: od.q, setting: '', length: 60, lines: od.a.map(([t, q]) => ({ role: 'pin', text: t, beat: 'answer', q })), house: true };
  } else if (kind === 'pin' || kind === 'utaneta' || kind === 'monomane' || kind === 'talk') {
    const style = kind === 'pin' ? (o.style || 'flip') : kind === 'talk' ? 'mandan' : kind;
    const bank = PIN[style] || PIN.flip;
    def = pickOf(bank, rng, o.title);
    lines = rows(def, dialect);
  } else {
    def = pickOf(MANZAI, rng, o.title);
    lines = rows(def, dialect);
  }
  return { id: 'house', kind, title: def.title, theme: def.theme || '', setting: def.setting || '', length: est(lines), lines, chars: def.chars || def.roles || null, house: true };
}

