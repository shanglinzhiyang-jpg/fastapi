//
//   bankNeta(kind, { style, dialect, rng, length, era, title }) → { title, theme, setting, length, lines, house: true }
//   MAKURA (落語のまくら topics by 客層), CROWD_TYPES, ODAI (大喜利のお題 + answers with q), MONOMANE subjects,
//   ADLIB lines, KAMI (噛み) helpers.

// tsukkomi text: 'Kansai｜standard'
const sel = (t, dialect) => {
  const s = String(t);
  const i = s.indexOf('｜');
  if (i < 0) return s;
  return dialect === 'std' ? s.slice(i + 1) : s.slice(0, i);
};

